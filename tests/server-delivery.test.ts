import {it, expect} from "vitest";
import {promises as fs} from "node:fs";
import path from "node:path";
import os from "node:os";
import {randomUUID} from "node:crypto";
import {ServerRuntime} from "../src/server/runtime";
import {openHttp} from "../src/server/http";
import {deliveryStatus} from "../src/server/delivery-view";

it.skipIf(process.platform !== "linux")("retains remote verification receipts across restart, rejects stale evidence, and serves them through authenticated HTTP", async () => {
  const base = await fs.mkdtemp(path.join(os.tmpdir(), "relay-remote-delivery-"));
  const workspace = path.join(base, "project"), root = path.join(base, "data");
  await fs.mkdir(workspace);
  let runtime = await ServerRuntime.open(root, undefined, [workspace]);
  let web: Awaited<ReturnType<typeof openHttp>> | undefined;
  try {
    await runtime.scheduler.dispatch(true);
    const job = await runtime.scheduler.add({title:"Verify real file", prompt:"Create report", cwd:workspace, mode:"cli", bucket:"codex", model:"", effort:"", approvalPolicy:"on-request", sandbox:"workspaceWrite", deliveryChecks:[{kind:"contains", label:"Result", path:"result.txt", text:"done"}]});
    job.state = "completed";
    const args = {requestId:randomUUID(), id:job.id, revision:1};
    const [first, duplicate]: any[] = await Promise.all([runtime.command("delivery.run", args), runtime.command("delivery.run", args)]);
    expect(first).toEqual(duplicate);
    expect(first).toMatchObject({state:"succeeded", result:{reports:[{status:"failed", findings:[{code:"missing"}]}]}});
    expect(job.state).toBe("needs_attention");
    expect(job.delivery!.reports).toHaveLength(1);
    expect(deliveryStatus(job.delivery)).toBe("验收未通过");
    expect(await runtime.command("delivery.repair", job.id)).toContain("result.txt");
    await fs.writeFile(path.join(workspace, "result.txt"), "done\n");
    await runtime.close();
    runtime = await ServerRuntime.open(root, undefined, [workspace]);
    expect(await runtime.command("delivery.run", args)).toEqual(first);
    const saved = runtime.store.data.jobs.find(j => j.id === job.id)!;
    expect(saved.delivery!.reports).toHaveLength(1);
    web = await openHttp(runtime, 0, [workspace]);
    const token = await fs.readFile(path.join(root, "http-token"), "utf8");
    const url = `http://127.0.0.1:${(web.server.address() as any).port}/api/command`;
    const post = (name:string, value:unknown, authorized=true, serverId=runtime.installationId) => fetch(url, {method:"POST", headers:{"Content-Type":"application/json", "X-Relay-Server-ID":serverId, ...(authorized?{Authorization:`Bearer ${token}`}:{})}, body:JSON.stringify({name, args:value})});
    const next = {requestId:randomUUID(), id:job.id, revision:1, reportId:first.result.reports[0].id};
    expect((await post("delivery.run", next, false)).status).toBe(401);
    expect((await post("delivery.run", next, true, randomUUID())).status).toBe(409);
    expect(saved.delivery!.reports).toHaveLength(1);
    const response = await post("delivery.run", next);
    expect(response.status).toBe(200);
    const passed: any = (await response.json()).result;
    expect(passed.state).toBe("succeeded");
    expect(passed.result.reports.at(-1).status).toBe("passed");
    expect(saved.state).toBe("completed");
    expect(deliveryStatus(saved.delivery)).toBe("最近检查通过");
    expect((await (await post("delivery.read", job.id)).json()).result.reports).toHaveLength(2);
    const stale: any = await runtime.command("delivery.run", {...next, requestId:randomUUID()});
    expect(stale.state).toBe("uncertain");
    expect(stale.error).toContain("已更新");
    expect(saved.delivery!.reports).toHaveLength(2);
    await runtime.scheduler.flagDeliveryEvidence(job.id, 1, passed.result.reports.at(-1).id, "changed");
    expect(deliveryStatus(saved.delivery)).toBe("交付证据已失效");
    saved.recoveryRequired = true;
    const unsafe: any = await runtime.command("delivery.run", {requestId:randomUUID(), id:job.id, revision:1, reportId:saved.delivery!.reports.at(-1)!.id});
    expect(unsafe.state).toBe("uncertain");
    expect(saved.delivery!.reports).toHaveLength(2);
    saved.recoveryRequired = false;
    const save = {requestId:randomUUID(), id:job.id, revision:1, checks:[{kind:"file", path:"other.txt", label:"New output", minBytes:1}]};
    const changed: any = (await (await post("delivery.save", save)).json()).result;
    expect(changed).toMatchObject({state:"succeeded",result:{revision:2}});
    expect(saved.delivery!.reports).toHaveLength(2);
    expect((await (await post("delivery.save", save)).json()).result).toEqual(changed);
    expect(saved.delivery!.revision).toBe(2);
    expect((await runtime.command("delivery.save", {...save, requestId:randomUUID()})) as any).toMatchObject({state:"uncertain"});
    await expect(runtime.command("delivery.save", {...save, requestId:randomUUID(), revision:2, checks:[{kind:"file",path:"../secret",label:"Escape"}]})).rejects.toThrow();
  } finally {
    await web?.close();
    await runtime.close();
    await fs.rm(base, {recursive:true, force:true});
  }
});
